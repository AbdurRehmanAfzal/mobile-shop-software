def entries() -> list[dict]:
    """every built-in line: the kind of product on its own, then once per brand"""
    out = []
    for name, kind, made_for, details, attr, options, brands in TYPES:
        base = {
            "kind": kind,
            "made_for": made_for,
            "details": details,
            "variant_by": attr,
            "variants": options,
        }
        out.append({"name": name, "brand": None, **base})
        out.extend({"name": f"{b} {name}", "brand": b, **base} for b in brands)
    return out
