def _each(prefix: str, items, suffix: str = "") -> list[str]:
    return [f"{prefix}{x}{suffix}" for x in items]


def _gen(prefix: str, lo: int, hi: int) -> list[str]:
    """EliteBook 840 G1 … G10"""
    return [f"{prefix} G{n}" for n in range(lo, hi + 1)]


def _genn(prefix: str, lo: int, hi: int) -> list[str]:
    """ThinkPad T14 Gen 1 … Gen 5"""
    return [f"{prefix} Gen {n}" for n in range(lo, hi + 1)]


