/** Owner: brand, model, storage and colour must be addable from the device form, and editable later. */

import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    if (!localStorage.getItem('locale')) localStorage.setItem('locale', 'en')
  })
})

test('add missing brand/model/storage/colour while adding a phone, then rename and delete', async ({ page }) => {
  await page.goto('/signup')
  await page.getByLabel('Shop name', { exact: true }).fill('Catalogue Shop')
  await page.getByLabel('Your name').fill('Owner')
  await page.getByLabel('Mobile number').fill(`039${Math.floor(10_000_000 + Math.random() * 89_999_999)}`)
  await page.getByLabel('Password').fill('e2e-secret-1')
  await page.getByRole('button', { name: /Create shop account/ }).click()
  await expect(page.getByPlaceholder("IMEI, phone or person's name")).toBeVisible()

  await page.goto('/stock/opening')
  await page.getByRole('button', { name: 'Add device' }).click()
  await page.getByLabel('IMEI', { exact: true }).fill('356938035643809')
  await page.getByRole('button', { name: 'New brand' }).click()
  await page.getByLabel('New brand').fill('Dcode')
  await page.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByRole('button', { name: 'New model' })).toBeVisible()
  await page.getByRole('button', { name: 'New model' }).click()
  await page.getByLabel('New model').fill('Bold 3')
  await page.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByRole('button', { name: 'Bold 3' })).toBeVisible()
  await page.getByRole('button', { name: 'New size' }).click()
  await page.getByLabel('New size').fill('48')
  await page.getByRole('button', { name: 'Save' }).click()
  await expect(page.locator('select').first()).toHaveValue(/.+/)
  await expect(page.locator('select').first().locator('option:checked')).toHaveText('48GB')
  await page.getByRole('button', { name: 'New colour' }).click()
  await page.getByLabel('New colour').fill('Mint')
  await page.getByRole('button', { name: 'Save' }).click()
  await expect(page.locator('select').last().locator('option:checked')).toHaveText('Mint')
  await page.getByLabel('Cost price').fill('5000')
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await expect(page.getByText('Dcode Bold 3')).toBeVisible()
  await page.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText('Purchase saved')).toBeVisible()

  // manage: Mint is used by the phone -> cannot delete; a new unused colour can be renamed and deleted
  await page.goto('/more/catalogue')
  await page.getByRole('button', { name: 'Colours' }).click()
  page.on('dialog', (d) => d.accept())
  await page.locator('main').getByRole('button', { name: 'New', exact: true }).click()
  await page.getByLabel('New', { exact: true }).fill('Lemon')
  await page.getByRole('button', { name: 'Save' }).click()
  const lemon = page.locator('div', { has: page.getByText('Lemon', { exact: true }) }).last()
  await lemon.getByRole('button', { name: 'Rename' }).click()
  await page.getByLabel('Type the name').fill('Lime')
  await page.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText('Lime', { exact: true })).toBeVisible()
  const mint = page.locator('div', { has: page.getByText('Mint', { exact: true }) }).last()
  await mint.getByRole('button', { name: 'Delete' }).click()
  await expect(page.getByText(/cannot be deleted/)).toBeVisible()
  const lime = page.locator('div', { has: page.getByText('Lime', { exact: true }) }).last()
  await lime.getByRole('button', { name: 'Delete' }).click()
  await expect(page.getByText('Lime', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Built-in').first()).toBeVisible()
  await page.screenshot({ path: 'test-results/catalogue.png', fullPage: true })
})
